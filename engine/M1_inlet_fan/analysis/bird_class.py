"""CS-E 800 bird class for the M1 fan (rules/bird_strike.md, analysis A-7 input).

Requirement basis: current CS-E 800 (Amendment 5) [K]. The 7B27 SAC type certificate basis was JAR-E
Change 8 plus Special Condition No. 1 "Bird strikes" (EASA TCDS E.004) [K]; M1 designs to CS-E 800.

The bird masses and numbers depend on the engine inlet throat area, an installation limitation set by
the applicant. The nacelle is out of scope, so the fan face area from the ICD stands in for it [T].
The output lists how far the proxy sits from the edges of its bands, i.e. how much the real throat area
may differ before the class changes.

Run: python -m engine.M1_inlet_fan.analysis.bird_class  (writes analysis/bird_class.yaml).
"""

import math
from pathlib import Path

from core.budgets import read_icd
from core.util import read_yaml, write_yaml

M1 = Path(__file__).resolve().parents[1]
TABLES = M1 / "rules" / "cs_e_800_birds.yaml"
OUT = M1 / "analysis" / "bird_class.yaml"


def band(bands: list[dict], area: float) -> dict:
    return next(b for b in bands if b["lower"] <= area and (b["upper"] is None or area < b["upper"]))


def margins(b: dict, area: float) -> dict:
    """Relative change of A that reaches the lower / upper band edge (null if none)."""
    return {"to_lower_edge": round(b["lower"] / area - 1, 4) if b["lower"] > 0 else None,
            "to_upper_edge": round(b["upper"] / area - 1, 4) if b["upper"] is not None else None}


def birds(spec: list) -> list[dict]:
    return [{"number": n, "mass_kg": m} for n, m in spec]


def classify(area: float, tables: dict) -> dict:
    large = band(tables["large_single"]["bands"], area)
    flock = band(tables["large_flocking"]["bands"], area)
    medium = band(tables["medium_flocking"]["bands"], area)
    small = tables["small"]
    core_bird = max((m for _, m in medium["engine_test"]), default=None)
    return {
        "large_single": {"birds": birds(large["birds"]), "speed_kn": tables["large_single"]["speed_kn"],
                         **margins(large, area)},
        "large_flocking": {"birds": birds(flock["birds"]), "applies": bool(flock["birds"]),
                           "speed_kn": tables["large_flocking"]["speed_kn"], **margins(flock, area)},
        "medium_flocking": {"engine_test": birds(medium["engine_test"]), "integrity": birds(medium["integrity"]),
                            **margins(medium, area)},
        "small": {"number": min(small["max_birds"], math.ceil(area / small["area_per_bird_m2"])),
                  "mass_kg": small["mass_kg"]},
        "core_flocking_bird_kg": core_bird,
    }


def run() -> dict:
    icd = read_icd("M1 bird class")
    proxy = icd["fan_face_area"]
    tables = read_yaml(TABLES)
    return {
        "description": "CS-E 800 (Amdt 5) bird class for the M1 fan; generated by "
                       "engine/M1_inlet_fan/analysis/bird_class.py, do not edit",
        "basis": {"design_to": "CS-E 800, Amendment 5 [K]",
                  "type_certificate_basis_7B27_SAC": "JAR-E Change 8 + Special Condition No. 1 'Bird strikes' "
                                                     "(EASA TCDS E.004) [K]; special condition text not read"},
        "inlet_throat_area": {"value": proxy["value"], "unit": proxy["unit"], "tag": "T",
                              "note": "proxy: fan face area from the ICD (M0 active revision); the real throat "
                                      "area is a nacelle limitation, out of scope"},
        "class": classify(proxy["value"], tables),
        "margin_note": "to_lower_edge / to_upper_edge = relative change of the throat area that moves it into "
                       "the next band",
    }


def main() -> None:
    result = run()
    write_yaml(OUT, result)
    c = result["class"]
    print(f"A = {result['inlet_throat_area']['value']} m2 [T]: large {c['large_single']['birds']}, "
          f"flocking applies {c['large_flocking']['applies']}, medium {c['medium_flocking']['engine_test']} "
          f"(lower edge {c['medium_flocking']['to_lower_edge']}), small {c['small']['number']}")


if __name__ == "__main__":
    main()
