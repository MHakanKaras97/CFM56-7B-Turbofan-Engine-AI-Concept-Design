"""M7 nozzle system design (rules/design.md R-D7.1-5): bypass duct and fan nozzle, turbine rear frame, core nozzle.

Inputs: read_icd("M7 design"), the M6 interfaces and the M1 fan frame layout (read-only import of
engine/M1_inlet_fan/geometry/fan_frame.build); design choices in analysis/nozzle_params.yaml. Writes
analysis/nozzle_results.yaml and the derived geometry/flowpath.yaml (for M8, M9).

Run: python -m engine.M7_nozzle.analysis.design
"""

import math
from pathlib import Path

from core.budgets import read_icd
from core.util import read_yaml, write_yaml
from tools import concept as C

HERE = Path(__file__).resolve().parent
PARAMS_FILE = HERE / "nozzle_params.yaml"
OUT_FILE = HERE / "nozzle_results.yaml"


def p(params: dict, key: str):
    return C.v(params[key])


def m1_frame() -> dict:
    """M1 fan frame aft ends (read-only): outer ring and wall ring M1.4.6."""
    from engine.M1_inlet_fan.geometry import fan_frame
    model = fan_frame.build()
    lay, parts = model["layout"], model["parts"]
    outer = parts["outer_ring"].BoundingBox()
    return {"x_outer_aft": float(lay["x1"]), "r_outer_in": float(lay["r_wall"]), "t_outer": float(lay["t_outer"]),
            "r_outer_out": float(outer.zmax), "x_wall_aft": float(lay["xc1"]), "r_wall_out": float(lay["r_root"]),
            "t_wall": float(lay["t_wall"]), "m1_revision": model["flowpath"]["revision"]}


def run(params: dict | None = None, icd: dict | None = None, m1: dict | None = None) -> dict:
    params = params or read_yaml(PARAMS_FILE)
    icd = icd or read_icd("M7 design")
    m1 = m1 or m1_frame()
    A18 = float(icd["modules"]["M7"]["budget"]["A18"]["value"])
    A8 = float(icd["modules"]["M7"]["budget"]["A8"]["value"])
    m6 = C.read_interface("M6")["interfaces"]
    s5 = m6["M7_station_5"]
    x5, rh5, rt5, swirl5 = (float(s5[k]) for k in ("x_m", "r_hub_m", "r_tip_m", "swirl_deg"))

    # R-D7.1 / R-D7.2 bypass duct and fan nozzle
    x18 = p(params, "fan_nozzle_exit_x")
    ri18 = p(params, "fan_nozzle_inner_radius")
    ro18 = math.sqrt(A18 / math.pi + ri18 ** 2)
    x_fn = x18 - p(params, "fan_nozzle_length")
    def r_outer(x):
        return C.lerp(m1["r_outer_in"], ro18, (x - m1["x_outer_aft"]) / (x18 - m1["x_outer_aft"]))
    bypass = {"outer": [(m1["x_outer_aft"], m1["r_outer_in"]), (x_fn, r_outer(x_fn)), (x18, ro18)],
              "inner": [(m1["x_wall_aft"], m1["r_wall_out"]), (x18, ri18)], "x_fan_nozzle": x_fn,
              "x18": x18, "r_in18": ri18, "r_out18": ro18, "A18": A18}
    # R-D7.3 TRF
    x_t0 = float(s5["x_rotor_aft_m"]) + p(params, "trf_gap")  # behind the stage 4 disk rim (M6)
    x6 = x_t0 + p(params, "trf_length")
    trf = {"x0": x_t0, "x1": x6, "r_hub": rh5, "r_tip": rt5, "n_struts": int(p(params, "trf_struts")),
           "chord": p(params, "trf_strut_chord_over_length") * p(params, "trf_length"), "swirl_in": swirl5}
    # R-D7.4 core nozzle
    x8 = x6 + p(params, "core_nozzle_length")
    rp8 = p(params, "plug_exit_radius_over_hub") * rh5
    ro8 = math.sqrt(A8 / math.pi + rp8 ** 2)
    nozzle = {"x6": x6, "x8": x8, "r_plug8": rp8, "r_sleeve8": ro8, "x_tip": x8 + p(params, "plug_tail_length"),
              "A8": A8}
    if not ro8 < rt5:
        raise ValueError("M7: core nozzle sleeve exit not inside the station 5 tip radius")
    return {"params": params, "icd_revision": icd["source"]["revision"], "m1": m1, "station_5": {"x": x5, "r_hub": rh5,
            "r_tip": rt5}, "bypass": bypass, "trf": trf, "nozzle": nozzle}


def _sec(d: dict) -> dict:
    return {k: (C.r6(v) if isinstance(v, float) else v) for k, v in d.items() if not isinstance(v, (dict, list))}


def to_yaml(res: dict) -> dict:
    return {"description": "M7 nozzle concept design results; generated by engine/M7_nozzle/analysis/design.py",
            "icd_revision": res["icd_revision"], "m1_frame": _sec(res["m1"]), "bypass": _sec(res["bypass"]),
            "trf": _sec(res["trf"]), "core_nozzle": _sec(res["nozzle"])}


def interface(res: dict) -> dict:
    b, trf, nz = res["bypass"], res["trf"], res["nozzle"]
    t = p(res["params"], "trf_wall_thickness")
    return {
        "description": "M7 nozzle interfaces; generated by engine/M7_nozzle/analysis/design.py, do not edit by hand",
        "icd_revision": res["icd_revision"],
        "interfaces": {
            "station_18": {"x_m": C.r6(b["x18"]), "r_inner_m": C.r6(b["r_in18"]), "r_outer_m": C.r6(b["r_out18"]),
                           "area_m2": C.r6(b["A18"]), "tag": "H", "note": "fan nozzle exit (R-D7.2)"},
            "station_8": {"x_m": C.r6(nz["x8"]), "r_plug_m": C.r6(nz["r_plug8"]), "r_sleeve_m": C.r6(nz["r_sleeve8"]),
                          "area_m2": C.r6(nz["A8"]), "tag": "H", "note": "core nozzle exit (R-D7.4)"},
            "M8_bearing_5_support": {"x_fwd_m": C.r6(trf["x0"]), "x_aft_m": C.r6(trf["x1"]),
                                     "r_m": C.r6(trf["r_hub"] - t), "tag": "H",
                                     "note": "TRF hub inner face; bearing #5 support (M8) hangs from it"},
            "bypass_inner_wall_x_r_m": [[C.r6(x), C.r6(r)] for x, r in b["inner"]],
            "bypass_outer_wall_x_r_m": [[C.r6(x), C.r6(r)] for x, r in b["outer"]],
        },
    }


def main() -> None:
    res = run()
    write_yaml(OUT_FILE, to_yaml(res))
    C.write_interface("M7", interface(res))
    print("M7 18", {k: round(v, 4) for k, v in res["bypass"].items() if isinstance(v, float)}, "8",
          {k: round(v, 4) for k, v in res["nozzle"].items()})


if __name__ == "__main__":
    main()
