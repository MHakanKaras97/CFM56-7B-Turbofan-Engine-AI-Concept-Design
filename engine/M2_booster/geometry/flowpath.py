"""M2 booster flowpath interfaces (concept level): annulus radii at the planes from the booster meanline and the
station 25 plane (rules/geometry.md R-G2.22).

Writes engine/M2_booster/geometry/flowpath.yaml (derived file, never edited by hand). Radii come from
analysis/booster_meanline.run (ICD via read_icd, M1 station 21 annulus, booster_params.yaml).
- interfaces.M3_station_25: HPC inlet plane for M3. The transition duct 24 -> 25 is the M1 frame core zone (hub ring
  M1.4.1, core struts M1.4.5, wall ring M1.4.6; CR-002/CR-003); its walls are the station 24 radii, so the station 25
  annulus is the station 24 annulus. x_m = aft end of the M1 frame core zone, read at run time from the M1 geometry
  code (fan_frame.build layout xc1, read-only import, never typed) [H].
- planes: hub/tip radii at station 21 and at every rotor TE / stator TE plane [T, plan step 5 annulus rule].

The M1 frame layout reads the M2 station 24 x and radii through layout.record (sha256 or radii check, R-G2.26), so
station_25 never depends on the station 25 fields of this file.

Run: python -m engine.M2_booster.geometry.flowpath
"""

import math
from pathlib import Path

from core.util import write_yaml
from engine.M2_booster.analysis import booster_meanline as bm

OUT_FILE = Path(__file__).resolve().parent / "flowpath.yaml"
M1_FRAME_SOURCE = "engine/M1_inlet_fan/geometry/fan_frame.py:layout (xc1, via build)"


def _r(x, n=6):
    return round(float(x), n)


def station_25() -> dict:
    """R-G2.22: station 25 plane = aft end of the M1 frame core zone (xc1), from the M1 geometry code [H]; with the
    station 24 x (M2 layout, start of the core zone) and the M1 hardware ends for the cross-check."""
    from engine.M1_inlet_fan.geometry import fan_frame
    model = fan_frame.build()
    lay, parts = model["layout"], model["parts"]
    return {"x25": float(lay["xc1"]), "x24": float(lay["xc0"]), "m1_revision": model["flowpath"]["revision"],
            "m2_revision": lay["m2_revision"], "r_hub_m1": float(lay["r_hub"]), "r_tip_m1": float(lay["r_split"]),
            "x_end_hub_ring": parts["hub_ring"].BoundingBox().xmax,
            "x_end_wall_ring": parts["wall_ring"].BoundingBox().xmax,
            "x_end_core_strut": parts["core_strut"].BoundingBox().xmax}


def build(res: dict | None = None, st25: dict | None = None) -> dict:
    res = res or bm.run()
    p24 = res["p24"]
    annulus = bm.p(res["params"], "annulus")
    planes = [{"plane": "station 21 (rotor 1 LE)", "r_hub_m": _r(res["p21"].r_hub), "r_tip_m": _r(res["p21"].r_tip)}]
    for s in res["stages"]:
        for name, pl in ((f"stage {s['stage']} rotor TE", s["rotor_exit"]), (f"stage {s['stage']} stator TE", s["stage_exit"])):
            planes.append({"plane": name, "r_hub_m": _r(pl.r_hub), "r_tip_m": _r(pl.r_tip)})
    st25 = st25 or station_25()
    return {
        "description": "M2 booster flowpath interfaces; generated by engine/M2_booster/geometry/flowpath.py, do not "
                       "edit by hand. Source: analysis/booster_meanline.run; station 25 x from the M1 geometry code.",
        "icd_revision": res["icd"]["source"]["revision"],
        "annulus_rule": {"value": annulus, "tag": "T", "note": "aero_method.md meanline plan step 5, lever L2"},
        "interfaces": {
            "M3_station_25": {
                "x_m": _r(st25["x25"]),
                "r_hub_m": _r(p24.r_hub), "r_tip_m": _r(p24.r_tip), "area_m2": _r(p24.area),
                "hub_tip": _r(p24.hub_tip, 4), "tag": "T",
                "note": f"HPC inlet plane (R-G2.22): x_m [H] = aft end of the M1 frame core zone ({M1_FRAME_SOURCE}, "
                        f"M1 {st25['m1_revision']}); transition duct 24 -> 25 = M1 frame core passage between hub "
                        f"ring M1.4.1 and wall ring M1.4.6 at the station 24 radii, so the station 25 annulus = "
                        f"station 24 annulus; M2 adds no duct part; Tt/Pt/W from the ICD",
            },
        },
        "planes": planes,
        "check": {"area_from_radii_m2": _r(math.pi * (p24.r_tip ** 2 - p24.r_hub ** 2))},
    }


def main() -> None:
    data = build()
    write_yaml(OUT_FILE, data)
    print("M3_station_25", data["interfaces"]["M3_station_25"])


if __name__ == "__main__":
    main()
