"""M4 combustor system design (rules/design.md R-D4.1-6): prediffuser, casing and liner sizing, station 4.

Inputs: read_icd("M4 design") and the M3 interfaces (engine/M3_hp_compressor/geometry/flowpath.yaml, read-only);
design choices in analysis/combustor_params.yaml. Writes analysis/combustor_results.yaml and the derived
geometry/flowpath.yaml (interfaces for M5).

Run: python -m engine.M4_combustor.analysis.design
"""

import math
from pathlib import Path

from core.budgets import read_icd
from core.util import read_yaml, write_yaml
from tools import concept as C

HERE = Path(__file__).resolve().parent
PARAMS_FILE = HERE / "combustor_params.yaml"
OUT_FILE = HERE / "combustor_results.yaml"


def p(params: dict, key: str):
    return C.v(params[key])


def run(params: dict | None = None, icd: dict | None = None) -> dict:
    params = params or read_yaml(PARAMS_FILE)
    icd = icd or read_icd("M4 design")
    st = icd["stations"]
    W31, T3, P3 = (float(st["31"][k]["value"]) for k in ("W", "Tt", "Pt"))
    W4, T4, P4, f4 = (float(st["4"][k]["value"]) for k in ("W", "Tt", "Pt", "FAR"))
    m3 = C.read_interface("M3")["interfaces"]
    s3 = m3["M4_station_3"]
    x3, rh3, rt3 = float(s3["x_m"]), float(s3["r_hub_m"]), float(s3["r_tip_m"])
    A3 = C.annulus_area(rh3, rt3)

    r_l = p(params, "liner_mean_radius")
    # R-D4.1 prediffuser
    A_pd = p(params, "prediffuser_area_ratio") * A3
    rh_pd, rt_pd = C.radii_mean(A_pd, r_l)
    x_pd = x3 + p(params, "prediffuser_length")
    # R-D4.2 casing
    _, R = C.gas_props(T3)
    rho3 = P3 * 1e3 / (R * T3)
    A_ref = W31 / (rho3 * p(params, "reference_velocity"))
    r_ci, r_co = C.radii_mean(A_ref, r_l)
    # R-D4.3 liner
    A_l = p(params, "liner_area_ratio") * A_ref
    rli, rlo = C.radii_mean(A_l, r_l)
    H = rlo - rli
    x_dome = x_pd + p(params, "dump_gap")
    L = p(params, "liner_length_over_height") * H
    x_str = x_dome + p(params, "liner_straight_fraction") * L
    x4 = x_dome + L
    # R-D4.4 station 4
    A4 = C.area_for(W4, T4, P4, p(params, "station4_mach"), f4)
    rh4, rt4 = C.radii_mean(A4, p(params, "station4_mean_radius"))
    if not (r_ci < rh_pd and rt_pd < r_co and r_ci < rli and rlo < r_co):
        raise ValueError("M4: prediffuser or liner outside the casing annulus")
    return {"params": params, "icd_revision": icd["source"]["revision"],
            "station_3": {"x": x3, "r_hub": rh3, "r_tip": rt3, "area": A3},
            "m3_case_flange": m3["M4_case_flange"],
            "prediffuser": {"x0": x3, "x1": x_pd, "r_hub1": rh_pd, "r_tip1": rt_pd, "area_exit": A_pd},
            "casing": {"A_ref": A_ref, "rho3": rho3, "r_in": r_ci, "r_out": r_co},
            "liner": {"area": A_l, "r_in": rli, "r_out": rlo, "height": H, "length": L, "x_dome": x_dome,
                      "x_straight_end": x_str, "x_exit": x4},
            "station_4": {"x": x4, "r_hub": rh4, "r_tip": rt4, "area": A4, "mach": p(params, "station4_mach")},
            "budget": {"burner_pr": P4 / P3, "T4": T4, "W4": W4}}


def to_yaml(res: dict) -> dict:
    def sec(d):
        return {k: C.r6(v) if isinstance(v, float) else v for k, v in d.items()}
    return {"description": "M4 combustor concept design results; generated by engine/M4_combustor/analysis/design.py",
            "icd_revision": res["icd_revision"], "prediffuser": sec(res["prediffuser"]), "casing": sec(res["casing"]),
            "liner": sec(res["liner"]), "station_4": sec(res["station_4"]),
            "burner_pr": {"value": C.r6(res["budget"]["burner_pr"]), "unit": "-", "tag": "H",
                          "note": "Pt4/Pt3 of the ICD (R-D4.6)"}}


def interface(res: dict) -> dict:
    s4, L, cs = res["station_4"], res["liner"], res["casing"]
    t = p(res["params"], "case_thickness")
    return {
        "description": "M4 combustor interfaces; generated by engine/M4_combustor/analysis/design.py, do not edit by hand",
        "icd_revision": res["icd_revision"],
        "interfaces": {
            "M5_station_4": {"x_m": C.r6(s4["x"]), "r_hub_m": C.r6(s4["r_hub"]), "r_tip_m": C.r6(s4["r_tip"]),
                             "area_m2": C.r6(s4["area"]), "tag": "H", "note": "liner exit = HPT NGV inlet (R-D4.4)"},
            "M5_outer_case_flange": {"x_m": C.r6(s4["x"]), "r_in_m": C.r6(cs["r_out"]), "r_out_m": C.r6(cs["r_out"] + t),
                                     "tag": "H", "note": "aft end of the combustor outer case; HPT case continues"},
            "M5_inner_case_flange": {"x_m": C.r6(s4["x"]), "r_m": C.r6(cs["r_in"]), "tag": "H",
                                     "note": "aft end of the combustor inner case (NGV inner support)"},
        },
    }


def main() -> None:
    res = run()
    write_yaml(OUT_FILE, to_yaml(res))
    C.write_interface("M4", interface(res))
    print("M4 station 4", {k: round(v, 4) for k, v in res["station_4"].items()})


if __name__ == "__main__":
    main()
