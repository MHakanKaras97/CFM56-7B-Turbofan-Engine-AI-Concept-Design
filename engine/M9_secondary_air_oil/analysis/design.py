"""M9 secondary air and oil system design (rules/design.md R-D9.1-4): drive train and oil system layout, secondary air
budget table, stage 5 bleed duct sizing.

Inputs: read_icd("M9 design"), M1 fan frame outer ring (read-only import), M3/M6/M7/M8 interfaces; design choices in
analysis/air_oil_params.yaml. Writes analysis/air_oil_results.yaml and geometry/flowpath.yaml.

Run: python -m engine.M9_secondary_air_oil.analysis.design
"""

import math
from pathlib import Path

from core.budgets import read_icd
from core.util import read_yaml, write_yaml
from tools import concept as C

HERE = Path(__file__).resolve().parent
PARAMS_FILE = HERE / "air_oil_params.yaml"
OUT_FILE = HERE / "air_oil_results.yaml"


def p(params: dict, key: str):
    return C.v(params[key])


def polar(x: float, r: float, deg: float) -> tuple[float, float, float]:
    """Point at radius r and clock angle deg about +X from +Z (same sense as tools/concept.rotate_x)."""
    a = math.radians(deg)
    return (x, -r * math.sin(a), r * math.cos(a))


def m1_ring() -> dict:
    from engine.M1_inlet_fan.geometry import fan_frame
    bb = fan_frame.build()["parts"]["outer_ring"].BoundingBox()
    return {"x0": float(bb.xmin), "x1": float(bb.xmax), "r_out": float(bb.zmax)}


def run(params: dict | None = None, icd: dict | None = None, ring: dict | None = None) -> dict:
    params = params or read_yaml(PARAMS_FILE)
    icd = icd or read_icd("M9 design")
    ring = ring or m1_ring()
    port = C.read_interface("M3")["interfaces"]["M9_bleed_port"]
    ret = C.read_interface("M6")["interfaces"]["M9_bleed_return"]
    r0 = ring["r_out"] + p(params, "clearance_over_ring")

    # R-D9.3 secondary air table and bleed duct
    air = []
    for f in icd["secondary_air"]["flows"]:
        air.append({"name": f["name"], "W": float(f["W"]["value"]), "fraction_of_W25": float(f["fraction_of_W25"]["value"]),
                    "extraction": str(f["extraction"]), "return": str(f["return"]), "return_module": f["return_module"],
                    "T_extraction": float(f["T_extraction"]["value"])})
    leak = next(a for a in air if a["name"] == "interstage_leak")
    bd = p(params, "bleed_duct")
    A = C.area_for(leak["W"], leak["T_extraction"], float(port["Pt_kpa"]), bd["mach"])
    r_bore = math.sqrt(A / math.pi)
    r_o = r_bore + bd["thickness"]
    x_port, x_ret = float(port["x_m"]), float(ret["x_m"])
    bleed = {"W": leak["W"], "Pt_port": float(port["Pt_kpa"]), "area": A, "r_bore": r_bore, "r_out": r_o,
             "thickness": bd["thickness"], "angle": bd["angle"],
             "path": [(x_port, float(port["r_case_out_m"]) + 0.002, bd["angle"]), (x_port, bd["r_route"], bd["angle"]),
                      (x_ret - 0.06, bd["r_route"], bd["angle"]),
                      (x_ret, float(ret["r_case_out_m"]) + r_o + 0.005, bd["angle"])]}

    # R-D9.1 drive train
    ig, tg, ag, ot = (p(params, k) for k in ("igb", "tgb", "agb", "oil_tank"))
    ds = p(params, "drive_shaft")
    tgb = dict(tg, r0=r0, r1=r0 + tg["height"])
    agb = dict(ag, r0=r0, r1=r0 + ag["height"])
    tank = dict(ot, r0=r0, r1=r0 + ot["height"])
    r_hds = r0 + 0.5 * tg["height"]
    a_t = tg["angle"] + math.degrees(tg["half_width"] / r_hds)
    a_a = ag["angle"] - math.degrees(ag["half_width"] / r_hds)
    hds = [(ds["hds_x"], r_hds, a_t), (ds["hds_x"], r_hds, 0.5 * (a_t + a_a)), (ds["hds_x"], r_hds, a_a)]
    rds = [(0.5 * (ig["x0"] + ig["x1"]), ig["r1"], ig["angle"]), (0.5 * (tg["x0"] + tg["x1"]), r0, tg["angle"])]

    # R-D9.2 oil lines
    ol = p(params, "oil_line")
    a_tank = ot["angle"] + math.degrees(ot["half_width"] / r_hds)
    fwd = [(ot["x0"] + 0.03, r_hds, a_tank)]
    steps = 4
    for i in range(1, steps + 1):
        fwd.append((ot["x0"] + 0.03, r_hds, a_tank + (ol["fwd_angle"] - a_tank) * i / steps))
    fwd += [(rds[1][0] - 0.04, r0 - 0.01, ol["fwd_angle"]), (rds[0][0] - 0.04, ol["fwd_end_r"], ol["fwd_angle"])]
    m7 = C.read_interface("M7")["interfaces"]
    x18 = float(m7["station_18"]["x_m"])
    s5 = m7["M8_bearing_5_support"]
    x_drop = 0.5 * (float(s5["x_fwd_m"]) + float(s5["x_aft_m"])) - 0.0
    aft = [(ol["aft_x0"], ol["aft_r"], ol["aft_angle"]), (x18 + 0.05, ol["aft_r"], ol["aft_angle"]),
           (x_drop - 0.12, ol["aft_rise_r"], ol["aft_angle"] / 2), (x_drop, ol["aft_rise_r"], 0.0),
           (x_drop, ol["aft_end_r"], 0.0)]
    return {"params": params, "icd_revision": icd["source"]["revision"], "ring": ring, "air": air, "bleed": bleed,
            "igb": ig, "tgb": tgb, "agb": agb, "tank": tank, "hds": hds, "rds": rds, "drive_shaft": ds,
            "oil_fwd": fwd, "oil_aft": aft, "oil_line": ol}


def to_yaml(res: dict) -> dict:
    b = res["bleed"]
    return {"description": "M9 secondary air and oil concept results; generated by "
                           "engine/M9_secondary_air_oil/analysis/design.py",
            "icd_revision": res["icd_revision"],
            "secondary_air": [{k: (C.r6(v) if isinstance(v, float) else v) for k, v in a.items()} for a in res["air"]],
            "bleed_duct": {"W": {"value": C.r6(b["W"]), "unit": "kg/s", "tag": "H"},
                           "Pt_port": {"value": C.r6(b["Pt_port"]), "unit": "kPa", "tag": "H"},
                           "area": {"value": C.r6(b["area"]), "unit": "m2", "tag": "H"},
                           "r_bore": {"value": C.r6(b["r_bore"]), "unit": "m", "tag": "H"}},
            "ring": {k: C.r6(v) for k, v in res["ring"].items()}}


def interface(res: dict) -> dict:
    return {"description": "M9 interfaces; generated by engine/M9_secondary_air_oil/analysis/design.py, do not edit by hand",
            "icd_revision": res["icd_revision"],
            "interfaces": {"bleed_duct_return": {"x_m": C.r6(res["bleed"]["path"][-1][0]), "tag": "H",
                                                 "note": "stage 5 bleed duct end on the LPT case (return 45, M6)"}}}


def main() -> None:
    res = run()
    write_yaml(OUT_FILE, to_yaml(res))
    C.write_interface("M9", interface(res))
    print("M9 bleed duct r_bore", round(res["bleed"]["r_bore"], 4), "ring", res["ring"])


if __name__ == "__main__":
    main()
